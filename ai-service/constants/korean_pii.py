"""한국어 PII 사전 감지 (Gemini 호출 전 사전 치환용).

배경: /mask의 Gemini 감지 단계는 이름·장소 '감지 자체'를 외부 LLM에 의뢰하므로,
정규식으로 못 잡은 PII는 감지되기 위해 원문이 Gemini를 거친다. 확실히 잡을 수
있는 한국어 PII를 여기서 사전에 치환해, 외부로 나가는 양을 줄인다.

설계 원칙 — 높은 정밀도, 낮은 재현율:
  이제는 사후가 아니라 '사전' 치환이다. 정상 단어를 잘못 가리면(과탐) LLM에 넘길
  텍스트가 망가진다. 반면 놓친 PII(미탐)는 어차피 Gemini가 2차로 잡는다. 그래서
  '확실한 앵커'가 있을 때만 잡는다:
    - 인명   : 성씨+이름 뒤에 직함 호칭(님/씨/선생님/…)이 붙은 경우만.
               앵커 없는 맨이름("철수랑 놀았어")은 Gemini로 넘긴다.
    - 기관명 : 고유부 + 기관 접미사(병원/의원/약국/센터/…).
    - 지명   : 광역 시·도 + 서울 자치구 '사전'. 동/읍/면은 접미사 과탐이 심해 제외.
"""
import re

# ── 인명: 성씨 + 이름 + 직함 호칭 ─────────────────────────────
# 흔한 한국 성씨. 호칭 앵커가 필수라, 성씨 시작 일반 단어(정말·강조 등)는
# 뒤에 호칭이 없어 걸리지 않는다.
_SURNAMES = (
    "김이박최정강조윤장임한오서신권황안송류유전홍고문양손배백허남심노하곽성차주"
    "우구민진지엄채원천방공현함변염여추도소석선설마길연위표명기반라왕금옥육인맹"
    "제모남탁국어은편용예봉한상순"
)

# 이름 뒤에 오면 인명임이 거의 확실한 직함/경칭.
# 관계어(이모·삼촌 등)는 이름 없이도 쓰여 앵커로 부적합하므로 제외.
_TITLES = "님|씨|여사|선생님|교수님|박사님|원장님|과장님|국장님|사장님|이사님|님께"

# 성씨(1자) + 이름(1~2자) 직후에 직함이 오는 경우. lookahead라 직함은 소비하지 않는다.
# "김순자님" → "김순자" 매치. "김씨"(이름 0자)는 매치되지 않는다.
_PERSON_TITLE = re.compile(
    rf"[{_SURNAMES}][가-힣]{{1,2}}(?=(?:{_TITLES}))"
)

# 이름(2~4자) + 공백 + 직함. "박영호 선생님" → "박영호".
_PERSON_SPACE_TITLE = re.compile(
    r"[가-힣]{2,4}(?=\s+(?:선생님|교수님|박사님|원장님|과장님|국장님|사장님|여사|씨|님))"
)

# ── 기관명: 고유부 + 기관 접미사 ─────────────────────────────
_ORG_SUFFIX = (
    "병원|의원|한의원|치과|약국|보건소|보건지소|의료원|요양원|요양병원|재활원|"
    "복지관|주민센터|행정복지센터|어린이집|유치원|초등학교|중학교|고등학교|"
    "대학교|대학|교회|성당|절"
)
# 접미사 앞에 최소 2자 고유부. "그 병원"(앞이 공백)은 걸리지 않는다.
_ORG = re.compile(rf"[가-힣A-Za-z0-9]{{2,12}}(?:{_ORG_SUFFIX})")

# ── 지명: 광역 시·도 + 서울 자치구 (사전 기반) ────────────────
# 동/읍/면/리 접미사는 일반어 과탐(운동·활동·라면·우리…)이 심해 사전으로만 잡는다.
_REGIONS = [
    # 광역 시·도
    "서울특별시", "부산광역시", "대구광역시", "인천광역시", "광주광역시",
    "대전광역시", "울산광역시", "세종특별자치시", "제주특별자치도",
    "경기도", "강원도", "강원특별자치도", "충청북도", "충청남도",
    "전라북도", "전북특별자치도", "전라남도", "경상북도", "경상남도",
    "서울", "부산", "대구", "인천", "광주", "대전", "울산", "세종",
    "경기", "강원", "충북", "충남", "전북", "전남", "경북", "경남", "제주",
    # 구어체 "○○시"(서울특별시의 축약형 등)
    "서울시", "부산시", "대구시", "인천시", "광주시", "대전시", "울산시", "세종시",
    # 서울 25개 자치구 (정적·유명해 사전화 합당)
    "강남구", "강동구", "강북구", "강서구", "관악구", "광진구", "구로구",
    "금천구", "노원구", "도봉구", "동대문구", "동작구", "마포구", "서대문구",
    "서초구", "성동구", "성북구", "송파구", "양천구", "영등포구", "용산구",
    "은평구", "종로구", "중구", "중랑구",
]
# 긴 지명부터 매치(서울특별시 > 서울). 뒤는 조사/공백/문장부호/끝 경계.
_REGION_ALT = "|".join(sorted(_REGIONS, key=len, reverse=True))
_PLACE = re.compile(
    rf"(?:{_REGION_ALT})(?=[\s,.!?)\]]|$|을|를|에|에서|의|으로|로|은|는|이|가|과|와|도|만|까지|부터)"
)


# 직함/호칭 명사 자체는 인명이 아니다. 성씨+글자 패턴에 오탐되므로 제외한다.
# (예: "선생님"의 "선생"은 성씨 "선"+"생"으로 잡힌다. "여사"의 "여"도 성씨.)
_NOT_A_NAME = {
    "선생", "여사", "교수", "박사", "원장", "과장", "국장", "사장", "이사",
    "부장", "차장", "회장", "실장", "팀장", "반장", "대리", "주임",
}


def detect_korean_pii(text: str) -> list[tuple[str, str]]:
    """텍스트에서 확실한 한국어 PII를 감지한다.

    Returns: (원본_문자열, "person" | "place") 목록. 중복 제거, 등장 순서 유지.
    호칭·접미사는 lookahead라 결과에 포함되지 않는다(이름/고유명만).
    """
    found: list[tuple[str, str]] = []
    seen: set[str] = set()

    def add(value: str, kind: str) -> None:
        v = value.strip()
        if v and v not in seen:
            seen.add(v)
            found.append((v, kind))

    for m in _PERSON_TITLE.finditer(text):
        if m.group() not in _NOT_A_NAME:
            add(m.group(), "person")
    for m in _PERSON_SPACE_TITLE.finditer(text):
        if m.group() not in _NOT_A_NAME:
            add(m.group(), "person")
    for m in _ORG.finditer(text):
        add(m.group(), "place")
    for m in _PLACE.finditer(text):
        add(m.group(), "place")

    return found
