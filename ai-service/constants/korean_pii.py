#
# 보호자가 가족을 소개하는 가장 전형적인 문장 형태인데 어느 패턴에도
# 안 걸렸다. 직함(_PERSON_TITLE)도 경칭(_PERSON_BARE_TITLE)도 없고,
# 사전(_PERSON_LEXICON)은 조사를 요구하는데 서술격 조사는 목록에 없었다.
#
# 서술격 조사가 붙는다는 것 자체가 "이것은 이름이다"라는 강한 앵커다.
# 성씨로 시작하는 것까지 요구해 일반명사 오탐을 막는다.
#
# 이름 길이를 3자로 못박는다. 2자까지 허용하면 성씨로 시작하는 두 글자
# 일반명사가 통째로 걸린다 — "마을이었어요"의 '마'가 성씨라 '마을'이
# 인명으로 잡혔다. 한국 성명은 대부분 3자이고, 2자 이름(김구)은 놓치더라도
# Gemini 계층이 한 번 더 본다. 과탐이 노트를 파괴하는 쪽이 더 나쁘다.
#
# "라고"는 따로 다룬다. "최영수라고"와 "마을이라고"는 구조가 같아서, 앞
# 규칙으로는 조사의 '이'를 이름 글자로 먹어 '마을이'가 인명이 된다.
# 이름 셋째 글자 자리에서 "이라고"가 시작하면 그 '이'는 조사다.
_PERSON_COPULA = re.compile(
    rf"(?<![가-힣])[{_SURNAMES}][가-힣]{{2}}"
    r"(?=(?:입니다|이에요|예요|이예요|이야|이라는))"
    r"|"
    rf"(?<![가-힣])[{_SURNAMES}][가-힣](?!이라고)[가-힣](?=라고)"
)

