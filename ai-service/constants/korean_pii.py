def detect_korean_pii(text: str) -> list[tuple[str, str]]:
    """텍스트에서 확실한 한국어 PII를 감지한다.

    Returns: (원본_문자열, "person" | "place") 목록. 중복 제거, 등장 순서 유지.
    호칭·접미사는 lookahead라 결과에 포함되지 않는다(이름/고유명만).
    """
    found: list[tuple[str, str]] = []
    seen: set[str] = set()

    def add(value: str, kind: str) -> None:
        v = value.strip()
        if v and v not in seen:
            seen.add(v)
            found.append((v, kind))

    for m in _PERSON_TITLE.finditer(text):
        if m.group() not in _NOT_A_NAME:
            add(m.group(), "person")
    for m in _PERSON_SPACE_TITLE.finditer(text):
        if m.group() not in _NOT_A_NAME:
            add(m.group(), "person")
    for m in _PERSON_COPULA.finditer(text):
        if m.group() not in _NOT_A_NAME and m.group() not in _KINSHIP_WORDS:
            add(m.group(), "person")
    for m in _PERSON_BARE_TITLE.finditer(text):
        if (
            m.group() not in _NOT_A_NAME
            and m.group() not in _KINSHIP_WORDS
            and m.group() not in _NOT_A_BARE_NAME
        ):
            add(m.group(), "person")

    # 관계어 + 이름 ("아들 원석"). group(1)이 이름이다.
    for m in _PERSON_KINSHIP.finditer(text):
        name = m.group(1)
        if (
            name not in _NOT_A_NAME
            and name not in _KINSHIP_WORDS
            and name not in _NOT_AFTER_KINSHIP
        ):
            add(name, "person")

    # 사전에 있는 맨이름 + 사람 조사 ("영희랑", "민수한테").
    # 사전에 없는 2~3자는 건드리지 않는다 — 일반명사 과탐을 막는 유일한 방어선이다.
    for m in _PERSON_LEXICON.finditer(text):
        name = m.group(1)
        if name in _GIVEN_NAMES:
            add(name, "person")

    for m in _ORG.finditer(text):
        add(m.group(), "place")
    for m in _PLACE.finditer(text):
        add(m.group(), "place")

    # 장소 접미사 — 블록리스트에 없을 때만.
    for m in _DONG.finditer(text):
        if m.group() not in _NOT_A_DONG:
            add(m.group(), "place")
    for m in _YEOK.finditer(text):
        if m.group() not in _NOT_A_YEOK:
            add(m.group(), "place")
    for m in _PARK.finditer(text):
        if m.group() not in _NOT_A_SIJANG:
            add(m.group(), "place")
    for m in _STREET_NUM.finditer(text):
        add(m.group(), "place")
    for m in _RI.finditer(text):
        if m.group() not in _NOT_A_RI and m.group() not in _KINSHIP_WORDS:
            add(m.group(), "place")

    return found
