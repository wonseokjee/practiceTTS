/**
 * 앱 로케일의 **단일 출처**.
 *
 * 예전에는 `'ko-KR'`이 STT·TTS·발화 캡처 여섯 곳에 각자 기본 인자로 박혀 있었다.
 * 값이 같아서 문제가 없어 보였지만, 언어를 늘리는 순간 **여섯 군데를 다 찾아야**
 * 하고 하나만 빠뜨리면 그 경로만 조용히 한국어로 남는다.
 *
 * 지금은 값이 상수 하나다. 앱 로케일이 생기면(Phase 1의 i18n) **여기 한 곳**이
 * 그 값을 받아 내려보내면 되고, 호출부는 그대로 둔다.
 *
 * 서버 쪽 짝은 `users.locale`(M27)이다 — 그쪽이 진짜 저장소이고, 이 상수는
 * 그 값이 프론트에 아직 안 내려오는 동안의 기본값이다.
 */
export const DEFAULT_LOCALE = 'ko-KR';

/**
 * 보호자가 읽는 화면(날짜 표기·대시보드·주간 리포트)의 로케일.
 *
 * **환자와 다를 수 있다.** 계획서가 로케일을 `patient_locale`/`caregiver_locale`
 * 둘로 나눈 이유가 이것이다 — 영어 보호자와 한국어 부모가 이 앱의 가장 개연성
 * 높은 초기 영어권 사용자다(계획 §3의 0-1). 지금은 값이 같지만, **축이 다르다는
 * 것**을 이름으로 남겨 둔다. 나중에 합쳐 놓은 것을 다시 가르는 것보다 싸다.
 *
 * 어느 기능이 어느 쪽을 따르는지는 계획서 §3의 0-1의 표가 정본이다.
 * 날짜·시각 표기는 **보고서를 읽는 사람** 기준이라 여기에 속한다.
 */
export const CAREGIVER_LOCALE = DEFAULT_LOCALE;

/**
 * 로케일에서 언어 코드만 — `ko-KR` → `ko`.
 *
 * 브라우저 음성 목록은 `ko-KR`·`ko` 처럼 정밀도가 제각각이라, 지역까지 맞는
 * 음성이 없을 때 언어만으로 한 번 더 찾아야 한다.
 */
export function languageOf(locale: string): string {
  return locale.split('-')[0];
}
