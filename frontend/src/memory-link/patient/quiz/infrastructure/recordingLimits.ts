// 녹음 길이 상한 — 화면 성격별로 다르다.
//
// 왜 필요한가: 예전에는 클라이언트에 상한이 아예 없었다. 무음 감지(10초)가
// 있지만 요양시설·거실은 TV 소리가 늘 있어 무음 판정이 안 나는 경우가 흔하고,
// 그러면 녹음이 끝나지 않고 메모리에 계속 쌓였다.
//
// 더 나쁜 건 실패하는 지점이었다. 서버 상한(5MB)에 걸리는 건 **업로드 시점**
// 이라, 환자가 3분을 말한 뒤에야 거부되고 답변이 통째로 사라졌다. 치매 환자에게
// 재수행은 그 자체로 부담이고, 반응시간·정확도가 달라져 임상 자료로도 못 쓴다.
//
// 그래서 클라이언트가 스스로 끊는다. 상한에 닿으면 거부가 아니라 **정상 인식**
// 으로 끝나므로 그때까지의 답변은 살아남는다. 서버 상한은 안전망으로만 남는다.

/** 16kHz mono 16bit PCM 기준 초당 바이트 (용량 환산용). */
export const BYTES_PER_SECOND = 16000 * 2;

/**
 * 퀴즈·검사 답변: 30초.
 *
 * 실제 답변은 3~15초다(그림 이름대기, 문장 완성, DDK 발음검사). 30초면
 * 가장 긴 경우의 2배이고, 그보다 길어지는 건 환자가 답을 못 찾고 헤매거나
 * 주변 소음이 녹음을 붙잡고 있는 상황이라 끊는 편이 낫다.
 */
export const QUIZ_RECORDING_LIMIT_MS = 30_000;

/**
 * 대화(회상) 모드: 120초.
 *
 * 어르신이 옛 기억을 길게 이야기하시는 것이 이 모드의 목적이므로 짧게 끊으면
 * 치료적으로 손해다.
 *
 * 주의: 현재 대화 모드는 브라우저 내장 STT(WebSpeechSttService)를 쓰므로 이
 * 값이 쓰이지 않는다. 자유 발화 서버 STT로 옮길 때 이 상수를 쓰면 되는데,
 * 그때는 **서버 크기 상한도 함께 확인**해야 한다. 120초 = 약 3.7MB다.
 */
export const CONVERSATION_RECORDING_LIMIT_MS = 120_000;
