// 소리가 안 났을 때 환자에게 보이는 안내
//
// 듣기가 문항의 전부인 과제가 있다(단어이해·문장이해·따라말하기). 소리가 안
// 나면 답할 수 없는데, 지금까지는 화면이 아무 말도 하지 않았다. 환자는 자기가
// 못 들은 건지 기계가 안 낸 건지 모른 채 아무거나 찍고 넘어간다. 그 기록이
// 남으면 못 들은 것이 못 알아들은 것으로 집계된다.
//
// **여기서 하는 일은 알리는 것까지다.** 채점은 건드리지 않는다 — 소리가 안 난
// 검사 문항을 도움받은 것(assisted)으로 볼지 무효로 볼지는 측정의 뜻을 정하는
// 문제라 따로 정해야 한다(TODO-110 후속).
//
// 문구는 세 화면이 똑같이 쓴다. 어르신에게는 같은 상황에 같은 말이 나오는 것이
// 정확한 말보다 중요하다. 그래서 컴포넌트로 묶어 한 곳에서만 고친다.
//
// **버튼 바로 위에 둔다.** 문구가 "아래 듣기 버튼"이라고 말하므로 위치가
// 곧 내용이다.

/** 세 화면이 공유하는 문구. 테스트가 이 상수로 확인한다. */
export const TTS_FAILURE_MESSAGE =
  '소리가 나오지 않았어요. 아래 듣기 버튼을 눌러 주세요.';

/**
 * TTS가 끝내 실패했을 때만 보인다.
 *
 * `useTTS`의 `error`는 서버(Azure)와 브라우저 음성이 **둘 다** 실패했을 때만
 * 찬다 — `AzureTtsService`가 서버 실패를 Web Speech로 받아내기 때문이다.
 * 그래서 이 안내가 뜨는 상황은 정말로 아무 소리도 안 난 상황이다.
 */
export function TtsFailureNotice() {
  return (
    // role="alert" — 같은 화면의 다른 상태 문구(SpeechInput·SpeechCaptureItem)와
    // 같은 방식이다. 스크린리더가 즉시 읽는다.
    <p className="text-base text-[#7A2E15]" role="alert">
      {TTS_FAILURE_MESSAGE}
    </p>
  );
}
