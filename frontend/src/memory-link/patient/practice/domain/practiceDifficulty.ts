// 문항을 만들고 연습이 그걸 그대로 받았기 때문이다.

/**
 * 연습이 넘지 않는 레벨.
 *
 * 레벨 2는 `LEVEL_CHOICE_SPEC` 기준 선택지 3개(정답 + 같은범주 1 + 무관 1)다.
 * 레벨 3(선택지 4, 같은범주 2)부터는 범주만으로 못 걸러 변별 부담이 붙는데,
 * 그건 측정에 좋은 성질이지 반복에 좋은 성질이 아니다.
 *
 * 검사 레벨이 5까지 올라가도 연습은 여기서 멈춘다. 잘하게 되면 검사에서
 * 어려운 것을 만나고, 연습에서는 계속 여러 번 되는 것을 한다.
 */
export const PRACTICE_MAX_LEVEL = 2;

/**
 * 검사 레벨을 연습 레벨로 옮긴다 — 올리지는 않고 낮추기만 한다.
 *
 * 아직 레벨을 읽어오는 배선이 없어 인자는 대부분 undefined로 들어온다.
 * 그때도 상한값을 돌려주므로 동작은 같다. 배선이 붙어도 이 함수만 지나면
 * 상한이 지켜진다.
 */
export function practiceLevelFor(examLevel?: number): number {
  if (examLevel == null) return PRACTICE_MAX_LEVEL;
  const clamped = Math.max(1, Math.min(5, Math.round(examLevel)));
  return Math.min(clamped, PRACTICE_MAX_LEVEL);
}

